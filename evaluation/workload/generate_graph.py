#!/usr/bin/env python3
"""Materialise a parameterised graph that actually spends its repair budget.

WHY THIS EXISTS
---------------
`thm:graph-termination` bounds total node executions by ``(1 + R) * Sigma_v max_attempts_v``. Every
shipped reference graph declares ``max_attempts: 1`` on every node and no repair budget at all, so
R = 0, the bound collapses to |V|, and the ``(1 + R)`` factor -- the part of the theorem that is
about repair rather than retry -- had never been exercised by anything.

That was not an oversight in the reference graphs. Until `loop_node_entry` published the controller's
repair round into the loop workspace, a loop node could not behave differently in round 1 than in
round 0, so a repair round provably re-ran identical work and produced an identical failure. Repair
was a no-op for any deterministic node, and declaring a budget for it would have been theatre.

With the round published, a gate can refuse until a named round, which gives a repair round
something to change and makes the whole mechanism observable without a single credential.

TWO CONDITIONS
--------------
`converging`     -- the gated node refuses in round 0 and passes once repair opens round 1.
                    Observes repair doing useful work and the run reaching DONE inside its budget.
`never-converges`-- the gated node refuses in every reachable round. Observes the GLOBAL round
                    bound being reached and respected: the suffix runs 1 + R times, then stops.

Usage:
    python3 generate_graph.py --dest /tmp/g --repair-budget 2 --require-round 1
"""

from __future__ import annotations

import argparse
import json
import pathlib
import subprocess
import sys
import textwrap

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from generate import materialise  # noqa: E402

REPO = HERE.parents[1]


def _digest(package: pathlib.Path) -> str:
    """Content digest of a loop package, via the shipped command that graphs are authored against."""
    done = subprocess.run(
        [sys.executable, "-m", "bounded_loops.cli", "graph", "digest", str(package), "--json"],
        capture_output=True, text=True, timeout=120, cwd=REPO,
    )
    if done.returncode != 0:
        raise SystemExit(f"bl graph digest failed for {package}:\n{done.stdout}\n{done.stderr}")
    try:
        payload = json.loads(done.stdout)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"bl graph digest emitted non-JSON: {exc}\n{done.stdout}") from exc
    # The field is named for where it is used: a graph node's `loop_package`.
    digest = payload.get("loop_package")
    if not isinstance(digest, str) or not digest.startswith("sha256:"):
        raise SystemExit(f"no loop_package digest in:\n{done.stdout}")
    return digest


def materialise_graph(
    dest: pathlib.Path,
    *,
    repair_budget: int = 2,
    max_attempts: int = 1,
    require_round: int = 1,
    n_records: int = 2,
) -> tuple[pathlib.Path, pathlib.Path]:
    """Write loop packages and a graph that routes their failure to repair.

    Returns ``(graph_path, loop_root)``. ``loop_root`` is passed to ``bl graph run --loop-roots``:
    packages resolve BY DIGEST, so a root only makes a package findable and cannot change which
    bytes a digest means.
    """
    packages = dest / "packages"
    prep = materialise(
        packages / "prep", n_records=n_records, policy="complete",
        max_iterations=4, no_progress_window=3,
    )
    # The gated node. `complete` means content is never the obstacle -- the ONLY thing standing
    # between this node and success is the repair round, which is what makes the measurement about
    # repair and not about the workload.
    check = materialise(
        packages / "check", n_records=n_records, policy="complete",
        max_iterations=4, no_progress_window=3, require_round=require_round,
    )

    graph = dest / "graph.yaml"
    graph.write_text(
        textwrap.dedent(f"""\
        # E9 repair-budget graph — GENERATED by evaluation/workload/generate_graph.py
        #
        # Keyless. `check` refuses until repair round {require_round}; failing it routes to repair
        # with `prep` as the target, so the reset suffix re-runs under a higher round.
        api_version: bounded-loops.dev/graph/v1
        graph_id: e9-repair-budget
        version: 1.0.0
        connection_slots: []
        nodes:
          - id: prep
            kind: loop
            loop_package: "{_digest(prep)}"
            inputs: {{}}
            outputs:
              verdict: internal
            budget:
              max_attempts: {max_attempts}
              max_wallclock_s: 300
            effects: []
            isolation: process_restricted
          - id: check
            kind: loop
            loop_package: "{_digest(check)}"
            inputs:
              source: internal
            outputs:
              verdict: internal
            budget:
              max_attempts: {max_attempts}
              max_wallclock_s: 300
            effects: []
            isolation: process_restricted
            on_failure:
              mode: repair
              target: prep
        edges:
          - from_node: prep
            from_port: verdict
            to_node: check
            to_port: source
            when: succeeded
        policies:
          # repair is only reachable under a continue mode: fail_closed stops the run at the
          # first node failure, so the repair edge could never fire. The validator refuses
          # that combination rather than compiling a graph whose declared repair is dead.
          fail_mode: continue_declared
          data_class: internal
          repair_budget: {repair_budget}
        """),
        encoding="utf-8",
    )
    return graph, packages


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dest", type=pathlib.Path, required=True)
    parser.add_argument("--repair-budget", type=int, default=2)
    parser.add_argument("--max-attempts", type=int, default=1)
    parser.add_argument("--require-round", type=int, default=1)
    parser.add_argument("--records", type=int, default=2)
    args = parser.parse_args()

    graph, packages = materialise_graph(
        args.dest,
        repair_budget=args.repair_budget,
        max_attempts=args.max_attempts,
        require_round=args.require_round,
        n_records=args.records,
    )
    print(f"graph:      {graph}")
    print(f"loop-roots: {packages}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
